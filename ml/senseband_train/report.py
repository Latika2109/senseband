"""Human-readable summary of ml/models/metrics.json -> ml/models/METRICS.md."""
from __future__ import annotations

import json
from pathlib import Path


def write_markdown(models_dir: Path) -> Path:
    m = json.loads((models_dir / "metrics.json").read_text())
    lines = ["# Model metrics", "", "Generated by `python -m senseband_train`. **Read the provenance column**: ",
             "simulated data proves the pipeline, not real-world accuracy.", "",
             "| model | data | provenance | target | result | met | size | ms (this laptop) |", "|---|---|---|---|---|---|---|---|"]
    for name, r in sorted(m.items()):
        t = r["target"]
        lines.append(f"| {name} | {', '.join(r['data']['sources'])[:70]} | {r['data']['provenance']} | "
                     f"{t['metric']} >= {t['value']} | {t['got']} | {'yes' if t['met'] else '**no**'}"
                     f"{'' if t.get('validated_on_real_data') else ' (not real data)'} | {r['onnx']['bytes'] // 1024} KB | "
                     f"{r['latency_ms_this_machine']['median']} |")
    lines += ["", "## Details", ""]
    for name, r in sorted(m.items()):
        lines += [f"### {name}", f"- notes: {r['data'].get('notes', '')}", f"- cv: {r['cv'].get('scheme')}"]
        for k in ("macro_f1", "accuracy", "af_f1", "sensitivity", "specificity", "mae_population_bpm", "mae_personalised_bpm"):
            v = r["cv"].get(k, r.get(k))
            if v is not None:
                lines.append(f"- {k}: {v:.3f}")
        for k, v in r.items():
            if k.startswith("rule_baseline"):
                lines.append(f"- {k}: {v}")
        lines.append("")
    out = models_dir / "METRICS.md"
    out.write_text("\n".join(lines))
    return out
